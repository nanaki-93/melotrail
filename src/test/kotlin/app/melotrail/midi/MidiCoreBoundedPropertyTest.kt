        const val RATIONAL_TIMING_SEED = 47_002
        const val AUTHORITY_TIMELINE_SEED = 47_003
        const val PROJECT_JSON_SEED = 47_004
        const val WRITER_READER_SEED = 47_005
        const val NOTE_PAIRING_SEED = 47_006
        const val MALFORMED_MIDI_CASES = 64
        const val NOTE_PAIRING_CASES = 48
        const val RATIONAL_TIMING_CASES = 128
        const val AUTHORITY_TIMELINE_CASES = 64
        const val PROJECT_JSON_CASES = 48
        const val WRITER_READER_CASES = 48
        const val MAX_MALFORMED_MIDI_BYTES = 128
        const val MAX_PROJECT_JSON_CHARS = 8_192
    }
