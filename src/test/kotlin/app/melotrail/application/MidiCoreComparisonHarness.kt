internal data class M01ComparisonCase(
    val id: String,
    val scenarioTags: Set<String>,
    val sourceBytes: ByteArray,
    val baselineAuthoritySha256: String,
    val meter: ProjectMeter,
    val occurrences: List<M01Occurrence>,
    val chords: List<M01Chord>,
    // This is the current complete-draft style whose authored 4/4 drum density
    // fits its role-validation budget. Freeze it rather than special-casing a
    // partial role package in the comparison baseline.
    val styleId: String = "steady-road",
    val seed: Long = 901L,
    val key: ProjectKey = ProjectKey(ProjectKeySpelling.C, ProjectScaleMode.MAJOR),
    val tempo: ProjectTempo = ProjectTempo(500_000),
    val pianoMelodyLoop: M01ReviewLoop,
    val fullArrangementLoop: M01ReviewLoop,
) {
    init {
        require(id.matches(Regex("[a-z0-9-]+"))) { "Comparison case ID is invalid" }
        require(scenarioTags.isNotEmpty()) { "Comparison case must identify its covered scenarios" }
        require(sourceBytes.isNotEmpty()) { "Comparison case source must not be empty" }
        require(baselineAuthoritySha256.matches(Regex("[0-9a-f]{64}"))) { "Comparison baseline authority hash is invalid" }
        require(occurrences.isNotEmpty()) { "Comparison case needs at least one occurrence" }
        require(chords.isNotEmpty()) { "Comparison case needs authoritative chords" }
        require(styleId.isNotBlank()) { "Comparison style is required" }
        val totalBars = occurrences.sumOf(M01Occurrence::bars)
        require(pianoMelodyLoop.endBar <= totalBars && fullArrangementLoop.endBar <= totalBars) {
            "Comparison review loops must remain within the authoritative structure"
        }
    }
}

internal data class M01ReviewLoop(val startBar: Int, val endBar: Int) {
    init { require(startBar > 0 && endBar >= startBar) { "Comparison review loop must cover one or more positive bars" } }

    override fun toString(): String = "bars $startBar–$endBar"

    fun toJson(): String = "{\"startBar\": $startBar, \"endBar\": $endBar}"
}

internal data class M01Occurrence(val id: String, val sectionId: String, val label: String, val bars: Int) {
    init { require(id.isNotBlank() && sectionId.isNotBlank() && label.isNotBlank() && bars > 0) }
}

internal data class M01Chord(
    val id: String,
    val occurrenceId: String,
    val symbol: String,
    val startTick: Long,
    val endTick: Long,
) {
    init { require(id.isNotBlank() && occurrenceId.isNotBlank() && symbol.isNotBlank() && startTick >= 0 && endTick > startTick) }
}

