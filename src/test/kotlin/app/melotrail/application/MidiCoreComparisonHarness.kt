    private data class RawNote(val start: Long, val pitch: Int, val end: Long)
    private fun note(start: Long, pitch: Int, end: Long) = RawNote(start, pitch, end)

    private fun rawMidi(numerator: Int, denominatorExponent: Int, notes: List<RawNote>, withExpression: Boolean = false): ByteArray {
        val conductor = track(trackName("Conductor"), tempo(), meter(numerator, denominatorExponent), end())
        val events = mutableListOf<RawEvent>()
        if (withExpression) {
            events += RawEvent(0, bytes(0xb0, 64, 127))
            events += RawEvent(480, bytes(0xe0, 0, 72))
            events += RawEvent(notes.maxOf(RawNote::end), bytes(0xb0, 64, 0))
        }
        notes.forEach { note ->
            events += RawEvent(note.start, bytes(0x90, note.pitch, 92))
            events += RawEvent(note.end, bytes(0x80, note.pitch, 48))
        }
        val melodyEvents = events.sortedWith(compareBy<RawEvent> { it.tick }.thenBy { it.data[0].toInt() and 0xff })
            .fold(Pair(0L, byteArrayOf())) { (last, bytes), event ->
                event.tick to (bytes + vlq((event.tick - last).toInt()) + event.data)
            }.second + end()
        // The fixture ticks are authored at the target workflow's 480 PPQ. The
        // header must use that same division so source extent and bar placement
        // remain authoritative and deterministic.
        return "MThd".encodeToByteArray() + bytes(0, 0, 0, 6, 0, 1, 0, 2, 1, 0xe0) + conductor + chunk("MTrk", trackName("Melody") + melodyEvents)
    }

    private data class RawEvent(val tick: Long, val data: ByteArray)
    private fun trackName(name: String): ByteArray = vlq(0) + bytes(0xff, 0x03, name.length) + name.encodeToByteArray()
    private fun tempo(): ByteArray = vlq(0) + bytes(0xff, 0x51, 3, 0x07, 0xa1, 0x20)
    private fun meter(numerator: Int, denominatorExponent: Int): ByteArray = vlq(0) + bytes(0xff, 0x58, 4, numerator, denominatorExponent, 24, 8)
    private fun end(): ByteArray = vlq(0) + bytes(0xff, 0x2f, 0)
    private fun track(vararg events: ByteArray): ByteArray = chunk("MTrk", events.fold(byteArrayOf()) { all, event -> all + event })
    private fun chunk(name: String, payload: ByteArray): ByteArray = name.encodeToByteArray() + bytes(payload.size ushr 24, payload.size ushr 16, payload.size ushr 8, payload.size) + payload
    private fun bytes(vararg values: Int): ByteArray = values.map(Int::toByte).toByteArray()
    private fun vlq(value: Int): ByteArray {
        require(value >= 0)
        val groups = mutableListOf<Int>()
        var remaining = value
        do { groups += remaining and 0x7f; remaining = remaining ushr 7 } while (remaining > 0)
        return groups.asReversed().mapIndexed { index, group -> (if (index == groups.lastIndex) group else group or 0x80).toByte() }.toByteArray()
    }
