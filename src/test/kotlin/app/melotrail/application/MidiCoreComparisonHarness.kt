        val exportManifestSha256: String,
    )
}

private fun m01SemanticDigest(path: Path): String {
    val inspection = JdkMidiReader().inspect(path)
    val canonical = inspection.sequence.tracks.joinToString("\n") { track ->
        "${track.index}|" + track.events.joinToString(";") { event -> event.toString() }
    }
    return m01Sha256(canonical.encodeToByteArray())
}

private fun m01Sha256(bytes: ByteArray): String =
    MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

internal fun m01FrozenInputsSha256(
    sourceSha256: String,
